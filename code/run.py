"""Portable v15 entry points. Restricted observations are external inputs."""
from __future__ import annotations

import argparse
import ast
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

CODE = Path(__file__).resolve().parent


def path_arg(parser, flag, help_text):
    parser.add_argument(flag, type=Path, required=True, help=help_text)


def parser():
    p = argparse.ArgumentParser(description=__doc__)
    sub = p.add_subparsers(dest="command", required=True)
    q = sub.add_parser("calibration", help="Run the original station model, QC, and validation")
    path_arg(q, "--data-dir", "Locally authorized fused station-overpass CSV directory")
    path_arg(q, "--metadata-file", "External Find_N.csv station metadata")
    path_arg(q, "--boundary", "External hydrological boundary shapefile")
    path_arg(q, "--output", "New ASCII output directory")
    q.add_argument("--settings", type=Path, default=CODE / "configuration/calibration_v15.json")
    q.add_argument("--workers", type=int, help="Override saved worker count without changing model settings")
    q = sub.add_parser("postprocess", help="Summarize saved predictions and compare empirical/SoS estimates")
    for flag, desc in [("--results-dir", "Completed model result directory"),
                       ("--metadata", "External station_metadata.csv"),
                       ("--station-audit", "External station_spatial_audit.csv"),
                       ("--sos-raw-dir", "External audited mapped SoS source records"),
                       ("--boundary", "External hydrological boundary shapefile"),
                       ("--output", "New output directory")]:
        path_arg(q, flag, desc)
    q.add_argument("--bootstrap", type=int, default=2000)
    q.add_argument("--skip-plots", action="store_true")
    q = sub.add_parser("upstream", help="Prepare/download/QC/fuse external inputs; download steps require network")
    path_arg(q, "--config", "Explicit JSON config; paths resolve relative to the working directory")
    q.add_argument("--steps", default="inventory,download,qc,attach,fuse,roughness,shift,audit")
    q.add_argument("--limit", type=int, help="Optional download limit for an explicitly requested smoke run")
    q = sub.add_parser("figure-cache", help="Prepare a LOCAL private figure cache from saved result tables")
    path_arg(q, "--data-root", "Private directory containing results/ and postprocess_results/")
    path_arg(q, "--output", "New cache/output directory; do not upload its pickle files")
    q = sub.add_parser("wse-domain", help="Summarize WSE position and normalized boundary distance")
    path_arg(q, "--data-root", "Private directory containing results/ and postprocess_results/")
    path_arg(q, "--base-cache", "LOCAL data.pkl generated by figure-cache")
    path_arg(q, "--output", "New domain-analysis directory; contains a private cache")
    q = sub.add_parser("statistics-figures", help="Build Figures 2, 3, 4, 6, S1, and S2 from a private cache")
    path_arg(q, "--domain-cache", "LOCAL data.pkl generated by wse-domain")
    path_arg(q, "--boundary", "External hydrological boundary shapefile")
    path_arg(q, "--output", "New figure directory")
    q = sub.add_parser("method-figure", help="Build the final conceptual Figure 1 without gauge data")
    q.add_argument("--background", type=Path, default=CODE.parent / "figures/assets/Fig1a_background.png")
    path_arg(q, "--output", "New figure directory")
    q = sub.add_parser("error-diagnostics", help="Reproduce Figure 5 and width/residual diagnostics without refitting")
    path_arg(q, "--data-root", "Private directory containing results/ and postprocess_results/")
    path_arg(q, "--output", "New diagnostic directory")
    return p


def require(paths, dirs=()):
    missing = [str(Path(x)) for x in paths if not Path(x).is_file()]
    missing += [str(Path(x)) for x in dirs if not Path(x).is_dir()]
    if missing:
        raise ValueError("Missing external inputs (these are not distributed):\n  " + "\n  ".join(missing))


def new_output(path):
    path = path.resolve()
    if path.exists() and (not path.is_dir() or any(path.iterdir())):
        raise ValueError("Choose a new, empty output directory: " + str(path))
    path.mkdir(parents=True, exist_ok=True)
    return path


def job(script, args=(), env=None):
    merged = os.environ.copy()
    merged.update({"PYTHONIOENCODING": "utf-8", "PYTHONUTF8": "1", "MPLBACKEND": "Agg"})
    merged.update(env or {})
    subprocess.run([sys.executable, str(CODE / script), *map(str, args)], env=merged, check=True)


def figure_names(output, mapping):
    """Add manuscript filenames alongside original renderer outputs."""
    for original, canonical in mapping.items():
        for extension in ["png", "svg", "pdf"]:
            for source in output.rglob(original + "." + extension):
                shutil.copy2(source, source.with_name(canonical + "." + extension))


def calibration(a):
    require([a.metadata_file, a.boundary, a.settings], [a.data_dir])
    if not any(a.data_dir.glob("*.csv")):
        raise ValueError("The fused station input directory contains no CSV files.")
    settings = json.loads(a.settings.read_text(encoding="utf-8"))
    if settings.get("seed", 20260723) != 20260723:
        raise ValueError("The retained original entry point uses the manuscript seed 20260723.")
    if not str(a.output.resolve()).isascii():
        raise ValueError("The original model requires an ASCII output path.")
    out = new_output(a.output)
    args = ["--data-dir", a.data_dir.resolve(), "--metadata-file", a.metadata_file.resolve(),
            "--basin-shapefile", a.boundary.resolve(), "--output-dir", out]
    keys = ["repeat_count", "ablation_repeat_count", "temporal_folds", "multistart_count",
            "bootstrap_iterations", "temporal_train_fraction", "validation_multistart_count",
            "objective", "beta_min", "beta_max", "beta_prior_weight", "width0_ratio_min",
            "width0_ratio_max", "optimizer_maxiter", "optimizer_popsize", "optimizer_tol",
            "local_optimizer_maxiter", "hampel_half_window", "hampel_min_points", "hampel_sigma",
            "wse_scale_floor_m", "width_scale_floor_m", "slope_log_scale_floor", "initial_neighbor_count",
            "initial_neighbor_radius_m", "initial_min_neighbors", "initial_width_ratio",
            "width_max_growth_m_per_m", "width_max_relative_growth_per_m"]
    for key in keys:
        if key in settings:
            args += ["--" + key.replace("_", "-"), settings[key]]
    args += ["--workers", a.workers or settings.get("workers", 20)]
    args += ["--sample-size-targets", ",".join(map(str, settings.get("sample_size_targets", [5, 10, 20])))]
    switches = {"run_temporal": "--no-temporal", "run_ablation": "--no-ablation",
                "run_ablation_reconstruction": "--no-ablation-reconstruction",
                "run_n_sensitivity": "--no-n-sensitivity", "run_beta_sensitivity": "--no-beta-sensitivity",
                "run_sample_size_analysis": "--no-sample-size-analysis", "run_multistart": "--no-multistart",
                "repeat_random_grouping": "--no-repeat-random-grouping", "use_parallel": "--serial"}
    for key, flag in switches.items():
        if settings.get(key) is False:
            args.append(flag)
    if settings.get("run_spatial_cv") is False:
        args.append("--no-spatial")
    if settings.get("fast"):
        args.append("--fast")
    if settings.get("max_stations"):
        args += ["--max-stations", settings["max_stations"]]
    job("calibration/run_beta_wse0_width0_experiments.py", args,
        {"OMP_NUM_THREADS": "1", "OPENBLAS_NUM_THREADS": "1", "MKL_NUM_THREADS": "1"})
    job("calibration/verify_swot5_results.py", ["--results-dir", out])


def postprocess(a):
    require([a.metadata, a.station_audit, a.boundary,
             a.results_dir / "tables/validation_predictions.csv",
             a.results_dir / "tables/parameter_estimates.csv",
             a.results_dir / "tables/validation_metrics_by_station.csv",
             a.results_dir / "run_configuration.json"], [a.sos_raw_dir])
    out = new_output(a.output)
    args = ["--results-dir", a.results_dir.resolve(), "--output-dir", out,
            "--metadata", a.metadata.resolve(), "--station-audit", a.station_audit.resolve(),
            "--sos-raw-dir", a.sos_raw_dir.resolve(), "--boundary-file", a.boundary.resolve(),
            "--bootstrap", a.bootstrap]
    if a.skip_plots:
        args.append("--skip-plots")
    job("postprocessing/analyze_postprocess.py", args)


def upstream(a):
    require([a.config])
    cfg = json.loads(a.config.read_text(encoding="utf-8"))
    steps = set(a.steps.split(","))
    paths = cfg.get("paths", {})
    files = []
    dirs = []
    for name in (["station_csv", "node_index_csv"] if "inventory" in steps else []):
        if name not in paths:
            raise ValueError("Explicit upstream config needs paths." + name)
        files.append(Path(paths[name]))
    if steps.intersection({"fuse", "shift"}):
        if "gauge_dir" not in paths:
            raise ValueError("Explicit upstream config needs paths.gauge_dir")
        dirs.append(Path(paths["gauge_dir"]))
    if "roughness" in steps:
        if "roughness_nc" not in paths:
            raise ValueError("Explicit upstream config needs paths.roughness_nc")
        files.append(Path(paths["roughness_nc"]))
    require(files, dirs)
    args = ["--config", a.config.resolve(), "--steps", a.steps]
    if a.limit is not None:
        args += ["--limit", a.limit]
    job("upstream/run_pipeline.py", args)


def figure_cache(a):
    # Read required filenames from the original preparer's own list, without reading data values.
    text = (CODE / "figures/prepare_data.py").read_text(encoding="utf-8")
    tree = ast.parse(text)
    small = next(ast.literal_eval(n.value) for n in tree.body if isinstance(n, ast.Assign)
                 and any(isinstance(t, ast.Name) and t.id == "small" for t in n.targets))
    needed = [a.data_root / folder / "tables" / (name + ".csv")
              for folder, names in small.items() for name in names]
    needed += [a.data_root / "results/tables" / (name + ".csv") for name in
               ["validation_predictions", "parameter_estimates", "width_curve_anchor_audit", "overpass_qc_audit"]]
    require(needed)
    out = new_output(a.output)
    job("figures/prepare_data.py", ["--data-root", a.data_root.resolve(), "--out", out,
                                   "--cache", out / "cache"])


def domain(a):
    require([a.base_cache, a.data_root / "results/tables/validation_predictions.csv"])
    out = new_output(a.output)
    job("figures/analyze_domain.py", env={"SWOT_RELEASE_OUTPUT": str(out),
        "SWOT_RELEASE_DATA_ROOT": str(a.data_root.resolve()),
        "SWOT_RELEASE_BASE_CACHE": str(a.base_cache.resolve())})


def statistics_figures(a):
    require([a.domain_cache, a.boundary])
    out = new_output(a.output)
    job("figures/build_statistics_figures.py", env={"SWOT_RELEASE_OUTPUT": str(out),
        "SWOT_RELEASE_DOMAIN_CACHE": str(a.domain_cache.resolve()),
        "SWOT_RELEASE_BOUNDARY": str(a.boundary.resolve())})
    figure_names(out, {"F02_sparse_constraints": "Figure_2", "F03_unused_states": "Figure_3",
                       "F04_wse_domain": "Figure_4", "F06_official_comparison": "Figure_6",
                       "S01_width_constraints": "Figure_S1", "S02_effective_parameters": "Figure_S2"})


def method_figure(a):
    require([a.background])
    out = new_output(a.output)
    job("figures/build_method_figure.py", env={"SWOT_RELEASE_OUTPUT": str(out),
        "SWOT_RELEASE_BACKGROUND": str(a.background.resolve())})


def error_diagnostics(a):
    needed = [a.data_root / "results/tables" / n for n in
              ["validation_predictions.csv", "parameter_estimates.csv"]]
    needed += [a.data_root / "postprocess_results/tables" / n for n in
               ["observation_diagnostics.csv", "pooled_screening_metrics.csv", "empirical_scale_comparison.csv"]]
    require(needed)
    out = new_output(a.output)
    comparison = out / "error_analysis"
    width = out / "width_analysis"
    comparison.mkdir()
    width.mkdir()
    env = {"SWOT_RELEASE_OUTPUT": str(width), "SWOT_RELEASE_DATA_ROOT": str(a.data_root.resolve()),
           "SWOT_RELEASE_ERROR_ANALYSIS": str(comparison)}
    job("diagnostics/analyze_errors.py", [a.data_root.resolve(), comparison], env)
    job("diagnostics/analyze_width.py", env=env)
    job("diagnostics/build_error_figure.py", env=env)
    figure_names(out, {"F05_extreme_errors_width": "Figure_5"})


def main():
    p = parser()
    a = p.parse_args()
    functions = {"calibration": calibration, "postprocess": postprocess, "upstream": upstream,
                 "figure-cache": figure_cache, "wse-domain": domain,
                 "statistics-figures": statistics_figures, "method-figure": method_figure,
                 "error-diagnostics": error_diagnostics}
    try:
        functions[a.command](a)
    except (ValueError, FileNotFoundError) as exc:
        p.error(str(exc))


if __name__ == "__main__":
    main()
